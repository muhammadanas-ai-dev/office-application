// Generate the licence audit (Day 27, hardening).
//
// Reads every installed npm dependency's package.json (from
// node_modules) and writes docs/LICENSES.md — a table of
// package, version and licence — plus the system tools and
// engines with their licences (which are not npm packages).
// Re-run it when dependencies change:
//   node scripts/license-audit.mjs
//
// The output is an INVENTORY, not a legal opinion. It flags
// the licences that need attention for a commercial release
// (AGPLv3, GPL) so the owner can decide the posture.

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(__dirname, "..");

function licenceOf(pkgJson) {
  if (typeof pkgJson.license === "string") return pkgJson.license;
  if (pkgJson.license?.type) return pkgJson.license.type;
  if (Array.isArray(pkgJson.licenses)) {
    return pkgJson.licenses.map((l) => l.type ?? l).join(", ");
  }
  return "UNKNOWN";
}

function main() {
  const root = JSON.parse(
    readFileSync(join(PROJECT_ROOT, "package.json"), "utf8")
  );
  const deps = { ...root.dependencies, ...root.devDependencies };
  const rows = [];
  for (const name of Object.keys(deps).sort()) {
    const pkgPath = join(PROJECT_ROOT, "node_modules", name, "package.json");
    let version = deps[name];
    let licence = "UNKNOWN";
    if (existsSync(pkgPath)) {
      const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
      version = pkg.version ?? version;
      licence = licenceOf(pkg);
    }
    rows.push({ name, version, licence });
  }

  const needsAttention = rows.filter((r) => /AGPL|GPL|LGPL/i.test(r.licence));

  const lines = [];
  lines.push("# Licences — Forma Office");
  lines.push("");
  lines.push("A licence inventory for the app, generated by");
  lines.push("`scripts/license-audit.mjs` (re-run it when dependencies");
  lines.push("change). This is an inventory, not a legal opinion — the");
  lines.push("owner decides the commercial licence posture.");
  lines.push("");
  lines.push("## npm dependencies");
  lines.push("");
  lines.push("| Package | Version | Licence |");
  lines.push("|---|---|---|");
  for (const r of rows) {
    lines.push(`| ${r.name} | ${r.version} | ${r.licence} |`);
  }
  lines.push("");
  lines.push("## System tools and engines (not npm packages)");
  lines.push("");
  lines.push("| Tool / engine | Licence | Notes |");
  lines.push("|---|---|---|");
  lines.push(
    "| ONLYOFFICE Docs (Community Edition) | AGPLv3 | The editor/converter engine. The owner decided on Day 1 he knows the licence — a proprietary commercial launch still needs the Developer licence + legal review (see ADR-001). |"
  );
  lines.push(
    "| Tesseract (OCR) | Apache 2.0 | Built from source in `ocr/`; the binary is in the repo. |"
  );
  lines.push(
    "| Leptonica (Tesseract's image library) | BSD 2-Clause | Built from source in `ocr/` (without TIFF support). |"
  );
  lines.push(
    "| qpdf (PDF security) | Apache 2.0 | A system binary; reinstall after a VM reset. |"
  );
  lines.push(
    "| LibreOffice (format conversion for the corpus) | MPL-2.0 | Used by the corpus generator only, not by the app at runtime. |"
  );
  lines.push(
    "| Ghostscript (PDF compression) | AGPLv3 | A system binary; used by the PDF compress tool. |"
  );
  lines.push(
    "| poppler-utils — pdftoppm (PDF rendering for OCR / image export) | GPLv2+ | A system binary. |"
  );
  lines.push(
    "| zip / unzip | BSD / Info-ZIP | System binaries; used by the image export. |"
  );
  lines.push("");
  lines.push("");
  lines.push("## Needs attention for a commercial release");
  lines.push("");
  lines.push("These licences have copyleft terms. Review them with a");
  lines.push("lawyer before a commercial release:");
  lines.push("");
  for (const r of needsAttention) {
    lines.push(`- **${r.name}** (${r.version}) — ${r.licence}`);
  }
  lines.push(
    "- **ONLYOFFICE Docs Community** — AGPLv3 (the editor/converter engine; see above)."
  );
  lines.push("- **Ghostscript** — AGPLv3 (PDF compression; see above).");
  lines.push(
    "- **poppler-utils (pdftoppm)** — GPLv2+ (PDF rendering for OCR / image export; see above)."
  );
  lines.push("");
  lines.push("## How this was generated");
  lines.push("");
  lines.push("`node scripts/license-audit.mjs` — it reads each installed");
  lines.push("package's own `package.json` in `node_modules`, so the");
  lines.push("licence listed is the one the package itself declares.");
  lines.push("The system tools and engines are listed by hand (they are");
  lines.push("not npm packages).");
  lines.push("");

  writeFileSync(join(PROJECT_ROOT, "docs", "LICENSES.md"), lines.join("\n"));
  console.log(`licences: wrote docs/LICENSES.md (${rows.length} npm packages)`);
  if (needsAttention.length > 0) {
    console.log(
      `licences: ${needsAttention.length} npm package(s) need attention: ${needsAttention.map((r) => r.name).join(", ")}`
    );
  }
}

main();
